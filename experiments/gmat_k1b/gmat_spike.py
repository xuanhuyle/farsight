"""GMAT spike: does the one-run-per-subprocess pattern hold, and is it deterministic?

Plan §17 weeks 1-2, spike (b): GMAT R2025a subprocess round-trip, information-gathering only.
GMAT is post-MVP (ADR-014, plan §17), so nothing in weeks 1-8 blocks on this. What it buys is
that the ADRs assert several things about GMAT nobody had tested:

  ADR-014  the API entry point is a distribution-local `load_gmat.py`  [UNVERIFIED in the ADR]
  ADR-014  GMAT R2025a supports Python 3.9-3.12, which is why 3.12 is pinned
  ADR-002  the engine is a per-process singleton with no reliable reset, so the execution unit
           must be one fresh OS process per run
  ADR-003  GMAT is the cross-check engine: configure-then-run, poor at mid-run intervention
  ADR-006  cross-engine comparison is Tier C, which presumes GMAT is at least self-consistent

Usage:
    python gmat_spike.py --gmat <path to GMAT_R2025a>          # parent: runs the whole spike
    python gmat_spike.py --gmat <path> --child <sma_km>        # one propagation, one process

The child mode is the point: every propagation happens in a process that has never seen GMAT
before, which is exactly ADR-002's execution model.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


def boot_gmat(gmat_root: Path):
    """Import and start the GMAT API from an application tree.

    This replicates what `api/load_gmat.py` does rather than importing it, because that file
    ships as a *template* carrying the literal placeholder `<TopLevelGMATFolder>` and will not
    run until someone edits it. An adapter cannot depend on a file the user has hand-edited, so
    it has to do this itself -- which is a concrete finding for the GMAT adapter, not a
    workaround for the spike.
    """
    bin_path = gmat_root / "bin"
    startup = bin_path / "api_startup_file.txt"
    if not startup.exists():
        raise SystemExit(
            f"missing {startup}. It is generated by `python api/BuildApiStartupFile.py`, "
            f"which rewrites the relative paths in gmat_startup_file.txt to absolute ones. "
            f"A GMAT install is not API-ready as shipped."
        )
    sys.path.insert(1, str(bin_path))
    os.chdir(bin_path)  # GMAT resolves data paths relative to cwd
    import gmatpy as gmat

    gmat.Setup(str(startup))
    return gmat


def propagate(gmat, sma_km: float, steps: int = 10, step_s: float = 60.0) -> dict:
    """Propagate a simple two-body orbit and return the final state.

    Deliberately minimal: what is under test is the API round-trip and its determinism, not
    astrodynamics. The force model is Earth point-mass only so that the answer is a property of
    the integrator rather than of a gravity file.
    """
    sat = gmat.Construct("Spacecraft", "Sat")
    sat.SetField("DateFormat", "UTCGregorian")
    sat.SetField("Epoch", "01 Jan 2026 00:00:00.000")
    sat.SetField("CoordinateSystem", "EarthMJ2000Eq")
    sat.SetField("DisplayStateType", "Keplerian")
    sat.SetField("SMA", sma_km)
    sat.SetField("ECC", 0.001)
    sat.SetField("INC", 28.5)
    sat.SetField("RAAN", 60.0)
    sat.SetField("AOP", 0.0)
    sat.SetField("TA", 0.0)

    earth = gmat.Construct("GravityField")
    earth.SetField("PotentialFile", "JGM2.cof")
    earth.SetField("Degree", 0)  # point mass: no oblateness, no data-file dependence
    earth.SetField("Order", 0)

    fm = gmat.Construct("ForceModel", "FM")
    fm.SetField("CentralBody", "Earth")
    fm.AddForce(earth)

    prop = gmat.Construct("Propagator", "Prop")
    integ = gmat.Construct("PrinceDormand78", "Integrator")
    integ.SetField("InitialStepSize", step_s)
    integ.SetField("Accuracy", 1.0e-12)
    prop.SetReference(integ)
    prop.SetReference(fm)

    gmat.Initialize()
    prop.AddPropObject(sat)
    prop.PrepareInternals()
    gator = prop.GetPropagator()
    gator.Step(0.0)
    gator.UpdateSpaceObject()

    for _ in range(steps):
        gator.Step(step_s)
        gator.UpdateSpaceObject()

    state = sat.GetState().GetState()
    return {
        "sma_in": sma_km,
        "final_state": [float(x) for x in state[:6]],
        "elapsed_s": steps * step_s,
    }


def run_child(gmat_root: Path, sma_km: float) -> dict:
    gmat = boot_gmat(gmat_root)
    return propagate(gmat, sma_km)


def run_in_subprocess(gmat_root: Path, sma_km: float) -> dict:
    out = subprocess.run(
        [sys.executable, os.path.abspath(__file__), "--gmat", str(gmat_root),
         "--child", str(sma_km)],
        capture_output=True, text=True, check=True,
    )
    for line in out.stdout.splitlines():
        if line.startswith("RESULT "):
            return json.loads(line[7:])
    raise RuntimeError(f"child produced no RESULT line.\nstdout:\n{out.stdout}\nstderr:\n{out.stderr}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gmat", required=True, type=Path)
    ap.add_argument("--child", type=float, default=None)
    args = ap.parse_args()

    if args.child is not None:
        print("RESULT " + json.dumps(run_child(args.gmat, args.child)))
        return 0

    print("=" * 78)
    print("GMAT SPIKE -- subprocess round-trip and determinism")
    print("=" * 78)
    print(f"  tree   : {args.gmat}")
    print(f"  python : {sys.version.split()[0]}")

    results: dict[str, bool] = {}

    print("\n" + "-" * 78)
    print("Q1  Does one propagation complete in a fresh subprocess?")
    print("-" * 78)
    a = run_in_subprocess(args.gmat, 7000.0)
    print(f"  final state: {[round(x, 6) for x in a['final_state']]}")
    results["q1_round_trip"] = len(a["final_state"]) == 6

    print("\n" + "-" * 78)
    print("Q2  Same inputs, two separate processes -> identical output? (ADR-006 Tier A)")
    print("-" * 78)
    b = run_in_subprocess(args.gmat, 7000.0)
    same = a["final_state"] == b["final_state"]
    print(f"  {'IDENTICAL' if same else 'DIFFERS'}")
    if not same:
        for i, (x, y) in enumerate(zip(a["final_state"], b["final_state"])):
            if x != y:
                print(f"    component {i}: {x!r} vs {y!r}  (delta {abs(x - y):.3e})")
    results["q2_cross_process_determinism"] = same

    print("\n" + "-" * 78)
    print("Q3  Different inputs -> different output? (guards a vacuous Q2)")
    print("-" * 78)
    c = run_in_subprocess(args.gmat, 8000.0)
    differs = a["final_state"] != c["final_state"]
    print(f"  SMA 7000 vs 8000 km: {'DIFFERS' if differs else 'IDENTICAL (inputs are inert!)'}")
    results["q3_inputs_bite"] = differs

    print("\n" + "-" * 78)
    print("Q4  A second setup in ONE process, with no reset (ADR-002's singleton claim)")
    print("-" * 78)
    gmat = boot_gmat(args.gmat)
    propagate(gmat, 7000.0)
    naive_reuse_raised = False
    try:
        propagate(gmat, 8000.0)  # a second Construct pass over a dirty engine
        print("  second run completed -- no residue from the first")
    except Exception as exc:  # noqa: BLE001 - the failure mode IS the finding
        naive_reuse_raised = True
        print(f"  raised: {type(exc).__name__}: {str(exc)[:150]}")
    results["q4_naive_reuse_fails"] = naive_reuse_raised

    print("\n" + "-" * 78)
    print("Q5  Does gmat.Clear() give a usable reset, and is the answer the SAME?")
    print("-" * 78)
    # This is the question that decides whether ADR-002's justification is accurate. A reset
    # that runs but returns a subtly different number is far more dangerous than one that
    # throws, so 'it worked' is not the finding -- 'it agreed bit-for-bit' is.
    gmat.Clear()
    after_clear = propagate(gmat, 8000.0)
    agrees = after_clear["final_state"] == c["final_state"]
    print(f"  reset ran         : yes")
    print(f"  agrees with a fresh process: {'BIT-IDENTICAL' if agrees else 'DIFFERS'}")
    if not agrees:
        for i, (x, y) in enumerate(zip(c["final_state"], after_clear["final_state"])):
            if x != y:
                print(f"    component {i}: {x!r} vs {y!r}")
    results["q5_clear_is_consistent_or_absent"] = agrees

    print("\n" + "=" * 78)
    print("VERDICT")
    print("=" * 78)
    for k, v in results.items():
        print(f"  {'PASS' if v else 'FAIL'}  {k}")
    ok = all(results.values())
    print(f"\n  GMAT spike: {'PASS' if ok else 'ATTENTION -- see above'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
